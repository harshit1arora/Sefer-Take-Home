// Traces fixture values back to the source PDFs. Invoice: exact check against the PDF text layer (fails on mismatch).
// Packing list and B/L are scans: OCR corroboration only (weak, informational; OCR is unreliable on these files).
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const dir = process.argv[2] ?? process.env.SEFER_SAMPLE_PDFS;
if (!dir) { console.error("Usage: node scripts/trace-source.mjs <folder with the three sample PDFs>\n(or set SEFER_SAMPLE_PDFS). Needs poppler (pdftotext/pdftoppm); the OCR part also needs tesseract. Use WSL on Windows."); process.exit(2); }
const fx = JSON.parse(readFileSync(new URL("../fixtures/sample-shipment.json", import.meta.url), "utf8"));
const num = (s) => Number(String(s).replace(/[(),]/g, ""));
const out = ["# Source trace", "", "Generated by `scripts/trace-source.mjs`.", "",
  "> **Sanitized for public release.** Style codes are shown as the sanitized fixture placeholders;",
  "> the source documents' own style codes are not reproduced. The numeric columns (quantities,",
  "> unit prices and printed amounts) are unchanged and are checked strictly against the invoice text layer.", ""];
// Resolve the three documents by role, tolerating filename variations (e.g. "..._House_BL.pdf" vs
// "..._House_Bill_Landing.pdf"). Returns undefined when a role is absent.
const { readdirSync } = await import("node:fs");
const files = readdirSync(dir);
const pick = (re) => files.find((f) => re.test(f) && /\.pdf$/i.test(f));
const invoiceFile = pick(/invoice/i);
const packingFile = pick(/pack/i);
const blFile = pick(/(lading|(^|[^a-z])bl([^a-z]|$)|bill)/i);
let bad = 0;

if (!invoiceFile) { console.error("No commercial-invoice PDF found in " + dir); process.exit(2); }
const inv = execFileSync("pdftotext", ["-layout", join(dir, invoiceFile), "-"], { encoding: "utf8" });
out.push("## Invoice (text layer, exact)", "", "| line | style | qty | unit price | printed amount | fixture matches |", "|---|---|---|---|---|---|");
const re = /^\s*(\d)\s+(\S+)\s+(.+?)\s+(\d{4}\.\d{2})\s+([\d,]+)\s+PCS\s+(\([\d.]+\)|[\d.]+)\s*\*?\s+(\([\d,]+\.\d{2}\)|[\d,]+\.\d{2})\s*$/;
const parsed = inv.split("\n").map((l) => re.exec(l)).filter(Boolean).map((m) => ({ lineNo: +m[1], style: m[2], qty: num(m[5]), price: num(m[6]), amount: num(m[7]) }));
for (const p of parsed) {
  const f = fx.invoice.lines.find((l) => l.lineNo === p.lineNo);
  // Styles are sanitized placeholders in the committed fixture, so they are compared informationally;
  // the numeric columns (quantity, unit price, printed amount) are still checked strictly.
  const ok = !!f && f.quantity === p.qty && f.unitPrice === p.price && f.statedAmount === p.amount;
  if (!ok) bad++;
  // The PDF's own style code is deliberately NOT reproduced (public repo); show the sanitized fixture style.
  const style = f ? f.style : `(line ${p.lineNo})`;
  out.push(`| ${p.lineNo} | ${style} | ${p.qty} | ${p.price} | ${p.amount.toFixed(2)} | ${ok ? "yes" : "NO"} |`);
}
if (parsed.length !== fx.invoice.lines.length) { bad++; out.push("", `Parsed ${parsed.length} lines, fixture has ${fx.invoice.lines.length}: MISMATCH`); }
const grab = (label) => { const m = new RegExp(label + "[^\\d]*([\\d,]+\\.\\d{2})").exec(inv); return m ? num(m[1]) : undefined; };
const totals = { "FOB total": [grab("TOTAL FOB VALUE \\(Items 1 - 4\\):"), fx.invoice.statedFobTotal], "Carried forward": [grab("SUB-TOTAL CARRIED FORWARD \\(USD\\):"), fx.invoice.statedSubtotalCarriedForward],
  Freight: [grab("Ocean Freight \\(Cat Lai - Tacoma\\):"), fx.invoice.freight], Insurance: [grab("Marine Insurance Premium:"), fx.invoice.insurance], "CIF total": [grab("TOTAL CIF TACOMA, WA \\(USD\\):"), fx.invoice.statedTotal] };
out.push("", "| invoice total | in PDF | in fixture | match |", "|---|---|---|---|");
for (const [k, [a, b]] of Object.entries(totals)) { const ok = a === b; if (!ok) bad++; out.push(`| ${k} | ${a} | ${b} | ${ok ? "yes" : "NO"} |`); }
const printedSum = parsed.filter((p) => p.lineNo <= 4).reduce((n, p) => n + p.amount, 0);
const recomputed = parsed.filter((p) => p.lineNo <= 4).reduce((n, p) => n + Math.round(p.qty * p.price * 100) / 100, 0);
out.push("", `Sum of printed amounts, lines 1-4: **${printedSum.toFixed(2)}**. Sum of qty x unit price: **${recomputed.toFixed(2)}**. Printed FOB total: **${totals["FOB total"][0]}**.`,
  "The printed T-shirt amount (6,480.00) is therefore a value PRINTED on the invoice that disagrees with 2,400 x 2.85 and with the invoice's own totals. It is preserved unchanged; the correction is only a suggestion.");

function ocr(file) {
  const d = mkdtempSync(join(tmpdir(), "ocr-"));
  try { execFileSync("pdftoppm", ["-r", "200", "-png", join(dir, file), join(d, "p")]); const png = join(d, "p-1.png");
    return execFileSync("tesseract", [png, "-", "--psm", "6"], { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }); }
  catch (e) { return ""; } finally { rmSync(d, { recursive: true, force: true }); }
}
const scans = [[packingFile, "Packing list", ["EXG-PL-2609-117", "1,888", "1,734", "13.58", "PACIFIC ARGOS", "BP-26-0918"]],
  [blFile, "House B/L", ["BMLVHCM26090001", "OPLUSGN26090001", "EXL7731482", "1,930", "13.580", "PACIFIC ARGOS"]]];
for (const [file, name, keys] of scans) {
  if (!file) { out.push("", `## ${name} (scan: OCR corroboration only, weak)`, "", "Document not found in the folder."); continue; }
  const text = ocr(file).replace(/\s+/g, " ");
  out.push("", `## ${name} (scan: OCR corroboration only, weak)`, "", text ? "| key value in fixture | found by OCR |" : "OCR unavailable.", text ? "|---|---|" : "");
  if (text) for (const k of keys) out.push(`| ${k} | ${text.includes(k) ? "yes" : "not found (OCR miss or mismatch; verify by eye)"} |`);
}
out.push("", "Values for the two scans in the fixture were transcribed visually; this script cannot prove them.");
writeFileSync(new URL("../docs/source-trace.md", import.meta.url), out.join("\n") + "\n");
console.log(out.join("\n"));
if (bad) { console.error(`\n${bad} invoice mismatch(es)`); process.exit(1); }
